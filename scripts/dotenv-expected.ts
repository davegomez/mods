import { parse } from "dotenv";
import { setValue } from "../blindfold/hooks/dotenv.ts";
import { parseCases, setValueCases } from "../blindfold/tests/dotenv-cases.ts";

const out = `${import.meta.dir}/../blindfold/tests/dotenv-expected.ts`;

const parsed = parseCases.map(({ input }) => ({ input, output: parse(input) }));

const set = setValueCases.map(({ base, name, value }) => {
	const result = setValue(base, name, value);
	return result.ok
		? {
				base,
				name,
				value,
				ok: true,
				before: parse(base),
				text: result.text,
				output: parse(result.text),
			}
		: { base, name, value, ok: false, reason: result.reason };
});

await Bun.write(
	out,
	`// Generated by \`bun scripts/dotenv-expected.ts\`. Do not edit by hand.
// biome-ignore-all lint/suspicious/noTemplateCurlyInString: saved test data holds a literal \${HOME}.
export const parseExpected: { input: string; output: Record<string, string> }[] = ${JSON.stringify(parsed)};

export const setValueExpected: ({ base: string; name: string; value: string } & (
	| { ok: true; before: Record<string, string>; text: string; output: Record<string, string> }
	| { ok: false; reason: string }
))[] = ${JSON.stringify(set)};
`,
);

const biome = Bun.spawn(
	["bunx", "@biomejs/biome@2.6.2", "format", "--write", out],
	{ stdout: "inherit", stderr: "inherit" },
);
if ((await biome.exited) !== 0) throw new Error("biome format failed");
